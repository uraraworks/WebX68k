* ---------------------------------------------------------------------------
* hostfs.s -- HostFS (feature/hostfs) のゲスト側ドライバ (HOSTFS.SYS)。
* remote-probe.s(観測用の実験コード、tools/x68/remote-probe.s)とは別の、
* 本番の配管用ドライバ。実測で確定したデバイスドライバ/リクエストヘッダの
* 形(remote-probe.sのコメント参照、親からの指示書にも同じ内容あり)に従う:
*
*   ドライバヘッダ: +0 次ヘッダへのリンク(L) / +4 属性(W) / +6 ストラテジ入口(L) /
*     +10 割り込みルーチン入口(L) / +14 名前(8B、ブロックデバイスは先頭1バイトが$20以下)。
*   リクエストヘッダ: +0 長さ / +1 ユニット番号 / +2 コマンドコード /
*     +3 状態low / +4 状態high / +5〜12 未使用 / +13〜 コマンドごと。
*
* このドライバは薄い転送役に徹する:
*   - ストラテジはA5(リクエストヘッダのポインタ)を保存するだけ。
*   - 割り込みルーチンは、コマンドが初期化($40)でも、まずリクエストヘッダの
*     アドレスをHostFSポートへ中継してホストへ「初期化要求が来た」ことを
*     知らせてから(通知。ホスト側はヘッダへは一切書き込まない想定)、
*     その後で自分の初期化応答(+13/+14/+18/+3/+4)を書く。順番が大事:
*     コアはJS側の受け口が無いとき安全策として+18に-2を書くことがあるが、
*     通知を先に行い応答を後で上書きすることで、常に正しいBPBテーブルの
*     ポインタで応答できる(親からの追加指示より)。
*   - それ以外(初期化以外)は、リクエストヘッダのアドレスをHostFSポート
*     ($e8c000、x68k/mem_wrap.cのHOSTFS_Write/Read参照)の+0〜+3へ
*     ビッグエンディアンで書き、+4を叩いてトリガし、+5(ステータス)が
*     0になるまで読み続ける。0になったら状態欄(+3/+4)を0にして、D0=0で
*     rts(実際の成功/エラーはJS側がヘッダ+18(戻り値)へ書き込み済み)。
*   - 上記2つの「ポートへ中継する」処理は relay_to_host(d1=リクエストヘッダの
*     ゲストアドレス)として共通化している。
*
* 属性ワードは$2000(bit13)固定でアセンブルする(remote-probe.sのC2以降の
* 本命と同じ値。実測で「ファイル単位の要求が来る」ことを確認済み)。
*
* 注意(過去の実験で3つとも踏んだ落とし穴):
*   1. d0 は movem で退避・復元してはいけない(rts時のHuman68kへの戻り値の
*      ため、push/popの対象からd0を外す)。
*   2. pushとpopの個数(レジスタリスト)を必ず揃える(ずれるとスタックが
*      壊れ、戻り先が化けてHuman68k自体がアドレスエラーで落ちる)。
*   3. 奇数番地へのワード書き込みはアドレスエラーになる。このドライバは
*      ポートI/O・状態欄のいずれも move.b (バイト単位)だけで行い、word/long
*      アクセスを一切使わないことでこの罠を回避している。起動画面へ出す
*      文字列(奇数長)のあとには必ず even を置き、以降のワード/ロング
*      データ(bpb等)が奇数番地から始まらないようにしている。
*
* 位置独立に書いてあり、ヘッダの2ロング(+6 ストラテジ入口 / +10 割り込み入口)
* だけ絶対番地が要る。hu_pack.py --reloc=6,10 で再配置テーブルを付ける
* (tools/x68/build-hostfs.sh参照)。
*
* --- 起動画面への案内(親からの指示書) ---
* CONFIG.SYSで組み込まれるとき(初期化コマンド$40)、起動画面へ
*   HostFS version <版番号> (WebX68k)
*   ホストのフォルダを <ドライブ>: に割り当てました
* の2行を案内する。<ドライブ>は初期化要求ヘッダの+22(実測で確定: 割り当て
* られたドライブ番号、0=A:、読むだけで書かない)に'A'を足した実際の文字を使う
* (固定文字にしない)。日本語(2行目)はソースの文字コードで化けるのを避ける
* ため、CP932のバイト列(Pythonの'…'.encode('cp932')で作成)で直接埋め込み、
* 元の文はコメントとして併記する。
*
* 表示の呼び出しは IOCS の B_PRINT ($21、A1=NUL終端文字列、trap #15)を使う。
* PRO-68Kマニュアル第6章「6.8 サンプルプログラム」(本のp.638〜641、
* PDFページ652〜655、_local/books/XC20_ProgManual.pdf)のプリンタドライバの
* 例(prnini/lptini、ラベルnormal:)が、まさにデバイスドライバの初期化
* ルーチンの中で trap #15 のIOCS呼び出し(moveq #$3c,d0 / trap #15、
* moveq #$3a,d0 / trap #15)を使い、続けて文字列表示(DOSコール_PRINT)まで
* 行っていることを示しており、「初期化ルーチン内でtrap #15呼び出しをして
* 安全」という裏付けになっている。同じ例はDOSコール_PRINT(pea 文字列 /
* dc.w _PRINT / addq.l #4,sp、トラップ命令が無い独特の呼び出し方)も使って
* いるが、_PRINTの正確なファンクション番号(doscall.mac依存)は手元の資料
* からは確認できなかったため、番号が確実なIOCSのB_PRINT($21)を代わりに
* 使う(呼び出し経路が初期化ルーチン内で安全、という同じ裏付けは変わらず
* 使える)。
