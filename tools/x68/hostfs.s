* ---------------------------------------------------------------------------
* hostfs.s -- HostFS (feature/hostfs) のゲスト側ドライバ (HOSTFS.SYS)。
* remote-probe.s(観測用の実験コード、tools/x68/remote-probe.s)とは別の、
* 本番の配管用ドライバ。実測で確定したデバイスドライバ/リクエストヘッダの
* 形(remote-probe.sのコメント参照、親からの指示書にも同じ内容あり)に従う:
*
*   ドライバヘッダ: +0 次ヘッダへのリンク(L) / +4 属性(W) / +6 ストラテジ入口(L) /
*     +10 割り込みルーチン入口(L) / +14 名前(8B、ブロックデバイスは先頭1バイトが$20以下)。
*   リクエストヘッダ: +0 長さ / +1 ユニット番号 / +2 コマンドコード /
*     +3 状態low / +4 状態high / +5〜12 未使用 / +13〜 コマンドごと。
*
* このドライバは薄い転送役に徹する:
*   - ストラテジはA5(リクエストヘッダのポインタ)を保存するだけ。
*   - 割り込みルーチンは、コマンドが初期化($40)ならその場で応答する
*     (C8-b/C3b と同じ、Human68kが起動時に必ず来るため一往復で済ませる)。
*   - それ以外は、リクエストヘッダのアドレスをHostFSポート($e8c000、
*     x68k/mem_wrap.cのHOSTFS_Write/Read参照)の+0〜+3へビッグエンディアンで
*     書き、+4を叩いてトリガし、+5(ステータス)が0になるまで読み続ける。
*     0になったら状態欄(+3/+4)を0にして、D0=0でrts(実際の成功/エラーは
*     JS側がヘッダ+18(戻り値)へ書き込み済み)。
*
* 属性ワードは$2000(bit13)固定でアセンブルする(remote-probe.sのC2以降の
* 本命と同じ値。実測で「ファイル単位の要求が来る」ことを確認済み)。
*
* 注意(過去の実験で3つとも踏んだ落とし穴):
*   1. d0 は movem で退避・復元してはいけない(rts時のHuman68kへの戻り値の
*      ため、push/popの対象からd0を外す)。
*   2. pushとpopの個数(レジスタリスト)を必ず揃える(ずれるとスタックが
*      壊れ、戻り先が化けてHuman68k自体がアドレスエラーで落ちる)。
*   3. 奇数番地へのワード書き込みはアドレスエラーになる。このドライバは
*      ポートI/O・状態欄のいずれも move.b (バイト単位)だけで行い、word/long
*      アクセスを一切使わないことでこの罠を回避している。
*
* 位置独立に書いてあり、ヘッダの2ロング(+6 ストラテジ入口 / +10 割り込み入口)
* だけ絶対番地が要る。hu_pack.py --reloc=6,10 で再配置テーブルを付ける
* (tools/x68/build-hostfs.sh参照)。
* ---------------------------------------------------------------------------

HOSTFS_PORT set $00e8c000

        section text

* --- デバイスドライバヘッダ (先頭26バイト) ---
drv_header:
        dc.l    $ffffffff      * +0  次ヘッダへのリンク(最後)
        dc.w    $2000          * +4  属性ワード(bit13 = ファイル単位の要求)
        dc.l    strategy       * +6  ストラテジ入口(要再配置)
        dc.l    interrupt      * +10 割り込みルーチン入口(要再配置)
        dc.b    $01            * +14 名前: ブロックデバイスなので先頭1バイトは$20以下
* +15 名前の残り7バイト
        dc.b    'HOSTFS1'

* --- ストラテジ入口: リクエストヘッダへのポインタ(A5)を保存するだけ ---
strategy:
        lea     req_ptr(pc),a0
        move.l  a5,(a0)
        rts

* --- 割り込みルーチン入口 ---
interrupt:
* d0はHuman68kへの戻り値なので退避・復元の対象から外す(落とし穴1)。
* a2はcmd_initのBPBテーブル組み立てで使うため、押す対象に含める。
        movem.l d1-d3/a0-a2,-(sp)

        lea     req_ptr(pc),a0
        move.l  (a0),a0                * a0 = リクエストヘッダへのポインタ

        moveq   #0,d0
        move.b  2(a0),d0                * コマンドコード(+2)
        cmp.b   #$40,d0
        beq.s   cmd_init

* --- 初期化以外: HostFSポートへ中継する ---
        move.l  a0,d1                   * d1 = リクエストヘッダのゲストアドレス

        move.l  d1,d2
        lsr.l   #8,d2
        lsr.l   #8,d2
        lsr.l   #8,d2                   * d2.b = アドレスの最上位バイト
        move.b  d2,HOSTFS_PORT+0

        move.l  d1,d2
        lsr.l   #8,d2
        lsr.l   #8,d2
        move.b  d2,HOSTFS_PORT+1

        move.l  d1,d2
        lsr.l   #8,d2
        move.b  d2,HOSTFS_PORT+2

        move.b  d1,HOSTFS_PORT+3        * d1.b = アドレスの最下位バイト

        move.b  #1,HOSTFS_PORT+4        * トリガ(書く値そのものは無視される)

relay_poll:
        move.b  HOSTFS_PORT+5,d2        * 0=完了 1=保留
        bne.s   relay_poll

* JS側がヘッダ+18(戻り値)へ書き終えている。状態欄(+3/+4)だけここで0にする。
        move.b  #$00,3(a0)
        move.b  #$00,4(a0)
        moveq   #0,d0
        bra.s   done

* --- 初期化コマンド($40) ---
cmd_init:
        move.b  #1,13(a0)               * +13 ユニット数 = 1

        lea     drv_end(pc),a1          * +14 ドライバの終わりアドレス
        move.l  a1,14(a0)

        lea     bpb(pc),a1
        lea     bpb_table(pc),a2
        move.l  a1,(a2)                 * bpb_table[0] = bpbの実番地

        move.l  a2,18(a0)               * +18 出力: BPBテーブルへのポインタ

        move.b  #$00,3(a0)
        move.b  #$00,4(a0)
        moveq   #0,d0

done:
* pushしたレジスタリストと完全に揃える(落とし穴2)。d0は含めない。
        movem.l (sp)+,d1-d3/a0-a2
        rts

* --- 作業領域(位置独立: すべてPC相対でアクセスする) ---
req_ptr:
        dc.l    0
bpb_table:
        dc.l    0                       * ユニット数1ぶん(BPBアドレス1個の配列)

* もっともらしいBPB(12バイト)。初期化以外はHostFSポート経由でJSが答えるため、
* 中身の正しさはHuman68kの起動を通す最低限でよい(1024B/セクタ・2HD相当)。
bpb:
        dc.w    1024                    * 1セクタのバイト数
        dc.b    1                       * 1クラスタのセクタ数
        dc.b    2                       * FAT数
        dc.w    1                       * 予約セクタ数
        dc.w    16                      * ルートエントリ数
        dc.w    1232                    * 全セクタ数(2HD相当)
        dc.b    $f9                     * メディアバイト
        dc.b    2                       * 1FATのセクタ数

drv_end:
