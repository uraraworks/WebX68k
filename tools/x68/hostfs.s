HOSTFS_PORT set $00e8c000

        section text

* --- デバイスドライバヘッダ (先頭26バイト) ---
drv_header:
        dc.l    $ffffffff      * +0  次ヘッダへのリンク(最後)
        dc.w    $2000          * +4  属性ワード(bit13 = ファイル単位の要求)
        dc.l    strategy       * +6  ストラテジ入口(要再配置)
        dc.l    interrupt      * +10 割り込みルーチン入口(要再配置)
        dc.b    $01            * +14 名前: ブロックデバイスなので先頭1バイトは$20以下
* +15 名前の残り7バイト
        dc.b    'HOSTFS1'

* --- ストラテジ入口: リクエストヘッダへのポインタ(A5)を保存するだけ ---
strategy:
        lea     req_ptr(pc),a0
        move.l  a5,(a0)
        rts

* --- 割り込みルーチン入口 ---
interrupt:
* d0はHuman68kへの戻り値なので退避・復元の対象から外す(落とし穴1)。
* a2はcmd_initのBPBテーブル組み立てで使うため、押す対象に含める。
        movem.l d1-d3/a0-a2,-(sp)

        lea     req_ptr(pc),a0
        move.l  (a0),a0                * a0 = リクエストヘッダへのポインタ

        moveq   #0,d0
        move.b  2(a0),d0                * コマンドコード(+2)
        cmp.b   #$40,d0
        beq.s   cmd_init

* --- 初期化以外: HostFSポートへ中継する ---
        move.l  a0,d1                   * d1 = リクエストヘッダのゲストアドレス
        bsr.w   relay_to_host
        moveq   #0,d0
        bra.s   done

* --- 初期化コマンド($40) ---
cmd_init:
* まずホストへ「初期化要求が来た」ことを通知する(応答を書く前に転送する。
* ファイル冒頭コメント参照。relay_to_hostは+3/+4(状態欄)しか書かないので、
* +13/+14/+18はこのあと自分で必ず正しい値に書き直す=上書きする)。
        move.l  a0,d1
        bsr.w   relay_to_host

* --- 割り当てられたドライブ名を起動画面へ案内する ---
        moveq   #0,d1
        move.b  22(a0),d1               * +22 割り当てられたドライブ番号(入力、0=A:、読むだけ)
        add.b   #'A',d1
        lea     msg2_drive(pc),a1
        move.b  d1,(a1)                 * 実行時に1バイトだけ書き換える(move.bなので奇数番地でも安全、落とし穴3)

* IOCS B_PRINT($21、A1=NUL終端文字列、trap #15)。ファイル冒頭コメント参照。
* a0(リクエストヘッダへのポインタ)はこの後も使うので、念のため退避する。
        movem.l a0,-(sp)
        lea     msg1(pc),a1
        moveq   #$21,d0
        trap    #15
        lea     msg2(pc),a1
        moveq   #$21,d0
        trap    #15
        movem.l (sp)+,a0

        move.b  #1,13(a0)               * +13 ユニット数 = 1

        lea     drv_end(pc),a1          * +14 ドライバの終わりアドレス
        move.l  a1,14(a0)

        lea     bpb(pc),a1
        lea     bpb_table(pc),a2
        move.l  a1,(a2)                 * bpb_table[0] = bpbの実番地

        move.l  a2,18(a0)               * +18 出力: BPBテーブルへのポインタ
                                         * (通知でJS側が-2等を書いていても、ここで必ず上書きする)

        move.b  #$00,3(a0)
        move.b  #$00,4(a0)
        moveq   #0,d0

done:
* pushしたレジスタリストと完全に揃える(落とし穴2)。d0は含めない。
        movem.l (sp)+,d1-d3/a0-a2
        rts

* --- HostFSポートへの中継(共通処理)。呼び出し前提: d1 = リクエストヘッダの
* ゲストアドレス、a0 = 同じリクエストヘッダへのポインタ(状態欄クリアに使う)。
* d2を破壊する。bsrで呼ぶだけなので他のレジスタ(a0含む)はそのまま。 ---
relay_to_host:
        move.l  d1,d2
        lsr.l   #8,d2
        lsr.l   #8,d2
        lsr.l   #8,d2                   * d2.b = アドレスの最上位バイト
        move.b  d2,HOSTFS_PORT+0

        move.l  d1,d2
        lsr.l   #8,d2
        lsr.l   #8,d2
        move.b  d2,HOSTFS_PORT+1

        move.l  d1,d2
        lsr.l   #8,d2
        move.b  d2,HOSTFS_PORT+2

        move.b  d1,HOSTFS_PORT+3        * d1.b = アドレスの最下位バイト

        move.b  #1,HOSTFS_PORT+4        * トリガ(書く値そのものは無視される)

relay_poll:
        move.b  HOSTFS_PORT+5,d2        * 0=完了 1=保留
        bne.s   relay_poll

* ホスト側が完了させた。状態欄(+3/+4)だけここで0にする
* (戻り値・出力欄はコマンドごとに呼び出し元が扱う)。
        move.b  #$00,3(a0)
        move.b  #$00,4(a0)
        rts

* --- 起動画面へ出す案内(ファイル冒頭コメント参照)。IOCS B_PRINT向けに
* NUL終端。奇数長の文字列のあとは必ずevenを置く(落とし穴3)。 ---
msg1:
        dc.b    13,10
        dc.b    'HostFS version 1.00 (WebX68k)'
        dc.b    13,10,0
        even

* "ホストのフォルダを <ドライブ>: に割り当てました" をCP932バイト列で埋め込む
* (Pythonの'…'.encode('cp932')で作成。シフトJIS指定だと0x5C周りがずれる
* 既知の落とし穴があるため、必ずcp932を使うこと)。<ドライブ>は
* msg2_drive(cmd_initで実行時に1バイト書き換える)。
msg2:
        dc.b    $83,$7a,$83,$58,$83,$67,$82,$cc,$83,$74,$83,$48,$83,$8b,$83,$5f,$82,$f0,$20
                                        * "ホストのフォルダを "
msg2_drive:
        dc.b    $00                     * ここへcmd_initが割り当てドライブの文字('A'+番号)を書く
        dc.b    $3a,$20,$82,$c9,$8a,$84,$82,$e8,$93,$96,$82,$c4,$82,$dc,$82,$b5,$82,$bd
                                        * ": に割り当てました"
        dc.b    13,10,0
        even

* --- 作業領域(位置独立: すべてPC相対でアクセスする) ---
req_ptr:
        dc.l    0
bpb_table:
        dc.l    0                       * ユニット数1ぶん(BPBアドレス1個の配列)

* もっともらしいBPB(12バイト)。初期化以外はHostFSポート経由でJSが答えるため、
* 中身の正しさはHuman68kの起動を通す最低限でよい(1024B/セクタ・2HD相当)。
bpb:
        dc.w    1024                    * 1セクタのバイト数
        dc.b    1                       * 1クラスタのセクタ数
        dc.b    2                       * FAT数
        dc.w    1                       * 予約セクタ数
        dc.w    16                      * ルートエントリ数
        dc.w    1232                    * 全セクタ数(2HD相当)
        dc.b    $f9                     * メディアバイト
        dc.b    2                       * 1FATのセクタ数

drv_end:
